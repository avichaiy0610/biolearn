export const bankForSubtopic = (subtopicId: string) => QUESTION_BANK.filter((b) => b.subtopicId === subtopicId);
export const bankForTopic = (topic: string) => QUESTION_BANK.filter((b) => b.topic === topic);

// Shape used by QuizGame: text answer + a per-option "why".
export function toQuizQuestion(b: BankQuestion) {
  return {
    id: `bank:${b.id}`,
    type: "mcq",
    question: b.question,
    options: b.options.map((o) => o.text),
    answer: b.options[b.correct].text,
    // The per-option "why" of the correct answer starts with "נכון." — drop it in
    // the summary box, which may follow a "✗ לא נכון" header.
    explanation: `התשובה הנכונה: ${b.options[b.correct].text}. ${b.options[b.correct].why.replace(/^נכון\.\s*/, "")}`,
    optionWhy: Object.fromEntries(b.options.map((o) => [o.text, o.why])),
    difficulty: b.difficulty,
    subtopicId: b.subtopicId,
    ref: b.ref,
  };
}
